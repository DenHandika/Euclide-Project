-- NIS belongs to a school. Keep existing values as optional metadata, never
-- reinterpret them as Euclide codes or rewrite historic user IDs.
ALTER TABLE euclide.student_profiles ALTER COLUMN nis DROP NOT NULL;
ALTER TABLE euclide.student_profiles DROP CONSTRAINT student_profiles_nis_key;
CREATE SEQUENCE euclide.student_code_sequence AS bigint NO CYCLE;
CREATE FUNCTION euclide.next_student_code() RETURNS text LANGUAGE plpgsql AS $$
DECLARE serial_number text;
BEGIN
  serial_number := nextval('euclide.student_code_sequence')::text;
  RETURN 'EUC-' || to_char(clock_timestamp() AT TIME ZONE 'Asia/Jakarta', 'YYYY')
    || '-' || lpad(serial_number, greatest(4, length(serial_number)), '0');
END;
$$;

ALTER TABLE euclide.student_profiles ADD COLUMN kode_siswa text;
UPDATE euclide.student_profiles SET kode_siswa = euclide.next_student_code();
ALTER TABLE euclide.student_profiles ALTER COLUMN kode_siswa SET NOT NULL;
ALTER TABLE euclide.student_profiles ADD CONSTRAINT student_profiles_code_unique UNIQUE (kode_siswa);
ALTER TABLE euclide.student_profiles ADD CONSTRAINT student_profiles_code_format
  CHECK (kode_siswa ~ '^EUC-[0-9]{4}-[0-9]{4,}$');

CREATE FUNCTION euclide.protect_student_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.kode_siswa IS NOT NULL THEN
      RAISE EXCEPTION 'Kode Siswa must be generated by Euclide';
    END IF;
    NEW.kode_siswa := euclide.next_student_code();
  ELSIF NEW.kode_siswa IS DISTINCT FROM OLD.kode_siswa OR NEW.user_id IS DISTINCT FROM OLD.user_id THEN
    RAISE EXCEPTION 'Student identity cannot be reassigned';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER student_identity_guard BEFORE INSERT OR UPDATE ON euclide.student_profiles
  FOR EACH ROW EXECUTE FUNCTION euclide.protect_student_identity();
